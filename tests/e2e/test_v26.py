import sys; sys.path.insert(0, sys.argv[-1]); from mock import handler, ARGS
from playwright.sync_api import sync_playwright
# v2.6: Chemicals and environment: California pesticide use by section (CDPR PUR), USGS county estimates, EPA TRI.
res=[]
def check(name, ok, info=''): res.append((name, bool(ok))); print(('PASS ' if ok else 'FAIL ')+name, info)
with sync_playwright() as p:
    b=p.chromium.launch(args=ARGS); pg=b.new_page(viewport={'width':1440,'height':900}); errs=[]
    pg.on('pageerror', lambda e: errs.append(getattr(e,'stack',str(e))[:400]))
    pg.route('**/*', handler); pg.add_init_script("try{localStorage.setItem('global-intelligence-atlas-version','2.12')}catch(e){}")
    pg.goto('http://localhost:8765/app/#@36.6,-119.8,0.4&l=borders,pur,pestus,tri', wait_until='commit'); pg.wait_for_timeout(13000)
    check('version 2.11', pg.evaluate("() => gia.VERSION")=='2.11')
    st=pg.evaluate("() => ['pur','pestus','tri'].map(id => [id, gia.state.lstatus[id]?.s, gia.state.data[id]?.rows?.length])")
    check('three chemical layers load from the regional-data branch', all(s=='ok' and n for _,s,n in st), st)
    g=pg.evaluate("() => [...document.querySelectorAll('#layer-list .group')].map(g => g.dataset.group)")
    check('a Chemicals and environment group', 'chem' in g, g)
    if not pg.evaluate("() => document.body.classList.contains('left-open')"): pg.click('.rail [data-section=layers]')
    pg.wait_for_timeout(800)
    ui=pg.evaluate("() => ({ sel: [...document.querySelectorAll('#pur-chem option')].map(o => o.value), bars: document.querySelectorAll('.mbars span').length, aerial: !!document.querySelector('#pur-aerial') })")
    check('chemical picker lists all and the chemicals with files', ui['sel'][:4]==['all','573','1601','136'], ui['sel'])
    check('monthly bars and the aerial box', ui['bars']==12 and ui['aerial'], ui)
    n_all=pg.evaluate("() => gia.state.data.pur.rows.length")
    pg.select_option('#pur-chem', '573'); pg.wait_for_timeout(2500)
    c=pg.evaluate("() => ({ chem: gia.state.data.pur.chem?.name, n: gia.state.data.pur.rows.length, note: gia.state.lstatus.pur.note })")
    check('choosing a chemical loads its sections', c['chem']=='1,3-DICHLOROPROPENE' and 0 < c['n'] < n_all, c)
    pg.evaluate("() => document.querySelector('#pur-aerial').scrollIntoView({block:'center'})"); pg.click('#pur-aerial'); pg.wait_for_timeout(2500)
    a=pg.evaluate("() => ({ n: gia.state.data.pur.rows.length, all: gia.state.data.pur.rows.every(r => r[3] > 0), note: gia.state.lstatus.pur.note })")
    check('aerial only keeps sections sprayed from the air', a['all'] and a['n'] < c['n'] and 'from the air' in a['note'], a)
    pg.click('#pur-aerial'); pg.select_option('#pur-chem', 'all'); pg.wait_for_timeout(2500)
    pg.evaluate("() => { const r = gia.state.data.pur.rows.find(r => r[2] === 123456); gia.select({ layer: 'pur', d: { r, chem: null } }); }"); pg.wait_for_timeout(1000)
    t=pg.inner_text('#notes-body')
    check('section card: pounds, aerial share, chemicals, crop, county, survey section', '123,456' in t and '81 %' in t and 'Almond' in t and 'Fresno' in t and 'section' in t.lower() and 'Mount Diablo' in t, t[:300])
    pts=pg.evaluate("() => { const ch = gia.state.chan?.pur; return ch ? { p: ch.particles?.length, pts: ch.points?.length } : null }")
    check('drawn as a few particle clouds plus clickable symbols near the view', pts and 1 <= pts['p'] <= 4 and pts['pts'] > 0, pts)
    pg.evaluate("() => { const d = gia.state.data.pestus; gia.select({ layer: 'pestus', d: { r: d.rows[0], compound: d.compound.name } }); }"); pg.wait_for_timeout(800)
    t=pg.inner_text('#notes-body')
    check('county card: estimate, intensity and top compounds', 'Glyphosate' in t and 'Adair County' in t and 'square mile' in t and 'Atrazine' in t, t[:300])
    pg.evaluate("() => gia.select({ layer: 'tri', d: gia.state.data.tri.rows[0] })"); pg.wait_for_timeout(800)
    t=pg.inner_text('#notes-body')
    check('facility card: releases, carcinogens and top chemicals', 'MOCK REFINERY' in t and '2,500,000' in t and 'Benzene' in t and 'carcinogen' in t.lower(), t[:300])
    calls=pg.evaluate("() => gia.globe.renderer().info.render.calls")
    check('draw calls stay batched', calls < 140, calls)
    check('no page errors', not errs, errs[:3])
    b.close()
print(f"SUMMARY {sum(1 for _,ok in res if ok)} / {len(res)}")
