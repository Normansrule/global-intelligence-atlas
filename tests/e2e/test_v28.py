import sys; sys.path.insert(0, sys.argv[-1]); from mock import handler, ARGS
from playwright.sync_api import sync_playwright
# v2.8: pesticides measured in rivers, lakes and wells (Water Quality Portal).
res=[]
def check(name, ok, info=''): res.append((name, bool(ok))); print(('PASS ' if ok else 'FAIL ')+name, info)
with sync_playwright() as p:
    b=p.chromium.launch(args=ARGS); pg=b.new_page(viewport={'width':1440,'height':900}); errs=[]
    pg.on('pageerror', lambda e: errs.append(getattr(e,'stack',str(e))[:400]))
    pg.route('**/*', handler); pg.add_init_script("try{localStorage.setItem('global-intelligence-atlas-version','2.10')}catch(e){}")
    pg.goto('http://localhost:8765/app/#@36.7,-119.8,0.5&l=borders,wqp', wait_until='commit'); pg.wait_for_timeout(12000)
    check('version 2.10', pg.evaluate("() => gia.VERSION")=='2.10')
    st=pg.evaluate("() => ({ s: gia.state.lstatus.wqp?.s, n: gia.state.data.wqp?.rows?.length, note: gia.state.data.wqp?.statusNote })")
    check('layer loads from the regional-data branch', st['s']=='ok' and st['n']==5 and 'above an EPA drinking-water limit' in (st['note'] or ''), st)
    if not pg.evaluate("() => document.body.classList.contains('left-open')"): pg.click('.rail [data-section=layers]')
    pg.wait_for_timeout(800)
    row=pg.evaluate("() => !!document.querySelector('label[for=ly-wqp]')")
    check('listed in the layer list', row)
    opts=pg.evaluate("() => [...document.querySelectorAll('#wqp-chem option')].map(o => o.value)")
    check('pesticide picker lists only pesticides that were sampled', opts[0]=='' and 'Atrazine' in opts and 'Imidacloprid' in opts and 'Fipronil' not in opts, opts)
    n=lambda: pg.evaluate("() => gia.state.chan.wqp.pick.length")
    n0=n()
    pg.select_option('#wqp-chem', 'Atrazine'); pg.wait_for_timeout(1200); n1=n()
    pg.select_option('#wqp-chem', ''); pg.select_option('#wqp-kind', 'well'); pg.wait_for_timeout(1200); n2=n()
    pg.check('#wqp-det'); pg.wait_for_timeout(1200); n3=n()
    pg.select_option('#wqp-kind', ''); pg.wait_for_timeout(1200); n4=n()
    check('filters: one pesticide, wells only, detections only', (n0, n1, n2, n3, n4)==(5, 1, 2, 2, 3), (n0, n1, n2, n3, n4))
    pg.uncheck('#wqp-det'); pg.wait_for_timeout(800)
    ch=pg.evaluate("() => gia.state.chan.wqp.particles.map(g => [g.color, g.pts.length])")
    check('four colour bands: not found, found, 1 µg/L or more, above the limit', [c for c,_ in ch]==['#8a96a8','#e3c45b','#ff8a4c','#ff4e6a'] and [k for _,k in ch]==[2,1,1,1], ch)
    pg.evaluate("() => gia.select({ layer: 'wqp', d: gia.state.data.wqp.rows[0] })"); pg.wait_for_timeout(900)
    t=pg.inner_text('#notes-body')
    href=pg.evaluate("() => [...document.querySelectorAll('#notes-body a')].map(a => a.href).find(h => h.includes('waterqualitydata.us'))")
    over=pg.evaluate("() => [...document.querySelectorAll('#notes-body .wqp-t tr.over td')].map(td => td.textContent)[0]")
    check('site card: table of pesticides, limit comparison and the raw-results link', 'Iowa River at Wapello' in t and '4.2 µg/L' in t and '8 of 20' in t and '140 %' in t and over=='Atrazine' and href and 'siteid=USGS-05465500' in href, (t[:300], href, over))
    pg.evaluate("() => gia.select({ layer: 'wqp', d: gia.state.data.wqp.rows[2] })"); pg.wait_for_timeout(900)
    t=pg.inner_text('#notes-body')
    check('small values shown in ng/L; no limit shown as none', '35 ng/L' in t and 'none' in t and 'Well or spring' in t, t[:300])
    m=pg.evaluate("() => gia.layerManifest().layers.find(l => l.id === 'wqp')")
    check('manifest names the Water Quality Portal and the EPA limits', m and [s['id'] for s in m['sources']]==['wqp','epamcl','regionaldata'] and all(s['name'] for s in m['sources']), m and m['sources'])
    calls=pg.evaluate("() => gia.globe.renderer().info.render.calls")
    check('draw calls stay batched', calls < 140, calls)
    check('no page errors', not errs, errs[:3])
    b.close()
print(f"SUMMARY {sum(1 for _,ok in res if ok)} / {len(res)}")
