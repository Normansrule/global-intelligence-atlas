/** Mix a CSS colour toward white (for the light parts of a glyph). */
export function lighten(color, f = 0.62) {
  const m = /^#([0-9a-f]{6})$/i.exec(color) ?? /^#([0-9a-f]{3})$/i.exec(color);
  let r; let g; let b;
  if (m && m[1].length === 6) { r = parseInt(m[1].slice(0, 2), 16); g = parseInt(m[1].slice(2, 4), 16); b = parseInt(m[1].slice(4, 6), 16); }
  else if (m) { [r, g, b] = [...m[1]].map((h) => parseInt(h + h, 16)); }
  else { const n = /rgba?\(([^)]+)\)/.exec(color); [r, g, b] = n ? n[1].split(',').map(Number) : [230, 236, 240]; }
  const k = (v) => Math.round(v + (255 - v) * f);
  return `rgb(${k(r)},${k(g)},${k(b)})`;
}
export const INK = '#07131f';

/** Inline SVG for the layer list and cards. */
export function glyphSvg(name, color, size = 18) {
  const parts = GLYPHS[name] ?? GLYPHS.pin; const light = lighten(color);
  const paint = (st) => (st.endsWith('d') ? INK : st.endsWith('l') ? light : color);
  const body = parts.map(([d, st, w]) => (st[0] === 's'
    ? `<path d="${d}" fill="none" stroke="${paint(st)}" stroke-width="${w ?? 2.2}" stroke-linecap="round" stroke-linejoin="round"/>`
    : `<path d="${d}" fill="${paint(st)}" fill-rule="evenodd"/>`)).join('');
  const halo = parts.map(([d, st, w]) => `<path d="${d}" fill="${st[0] === 's' ? 'none' : INK}" stroke="${INK}" stroke-width="${(st[0] === 's' ? (w ?? 2.2) : 0) + 2.2}" stroke-linecap="round" stroke-linejoin="round" fill-rule="evenodd"/>`).join('');
  return `<svg class="glyph" viewBox="-1.5 -1.5 27 27" width="${size}" height="${size}" aria-hidden="true">${halo}${body}</svg>`;
}

/** One flat Isotype unit: the glyph in a single colour (currentColor), details knocked out to the panel colour.
 *  Used for counted rows, where every unit stands for the same number of things. */
export function unitSvg(name, size = 16) {
  const parts = GLYPHS[name] ?? GLYPHS.pin;
  const body = parts.map(([d, st, w]) => (st[0] === 's'
    ? `<path d="${d}" fill="none" stroke="currentColor" stroke-width="${w ?? 2.2}" stroke-linecap="round" stroke-linejoin="round"${st.endsWith('d') ? ' style="stroke:var(--panel)"' : ''}/>`
    : `<path d="${d}" fill="currentColor" fill-rule="evenodd"${st.endsWith('d') ? ' style="fill:var(--panel)"' : ''}/>`)).join('');
  return `<svg class="unit" viewBox="-1.5 -1.5 27 27" width="${size}" height="${size}" aria-hidden="true">${body}</svg>`;
}

